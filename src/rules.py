"""
Traditional Rule-Based WAF Engine Module (Phase 05)
Implements deterministic regex matching, risk scoring, explainable rule triggers,
and calibrated three-way decisions (ALLOW, BLOCK, REVIEW).
"""

import json
import pathlib
import re
import time
from typing import Dict, Any, List, Optional, Tuple
import pandas as pd


class TraditionalRuleEngine:
    """
    Deterministic signature-based WAF rule engine.
    Serves as the empirical baseline for experimental comparison with AI models.
    """

    def __init__(self, config_path: Optional[str] = None):
        if config_path is None:
            config_path = str(pathlib.Path(__file__).resolve().parent.parent / "config" / "rules.json")

        self.config_path = config_path
        self.rules: List[Dict[str, Any]] = []
        self.compiled_rules: List[Tuple[Dict[str, Any], re.Pattern]] = []
        self.block_threshold = 0.70
        self.review_threshold = 0.35

        self.load_rules(config_path)

    def load_rules(self, config_path: str):
        """Load and compile rule specifications from JSON configuration."""
        with open(config_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        self.rules = data.get("rules", [])
        thresholds = data.get("default_thresholds", {})
        self.block_threshold = thresholds.get("block_threshold", 0.70)
        self.review_threshold = thresholds.get("review_threshold", 0.35)

        self.compiled_rules = []
        for r in self.rules:
            pattern_str = r["pattern"]
            compiled_pat = re.compile(pattern_str, re.IGNORECASE | re.DOTALL)
            self.compiled_rules.append((r, compiled_pat))

        print(f"[TraditionalRuleEngine] Loaded and compiled {len(self.compiled_rules)} security rules from {config_path}")

    def evaluate_payload(self, payload: str) -> Dict[str, Any]:
        """
        Evaluates a normalized HTTP request string against the rule library.
        Returns risk score, matched rule list, verdict, and latency.
        """
        start_time = time.perf_counter()
        if not payload or not isinstance(payload, str):
            payload = ""

        matched_rules: List[Dict[str, Any]] = []
        highest_weight = 0.0

        for rule, compiled_pat in self.compiled_rules:
            match = compiled_pat.search(payload)
            if match:
                weight = float(rule.get("weight", 0.5))
                if weight > highest_weight:
                    highest_weight = weight

                matched_rules.append({
                    "id": rule["id"],
                    "name": rule["name"],
                    "category": rule["category"],
                    "weight": weight,
                    "matched_substring": match.group(0)[:60]  # truncate long match
                })

        # Calculate bounded risk score using highest matching weight
        risk_score = highest_weight

        # Three-way decision policy
        if risk_score >= self.block_threshold:
            verdict = "BLOCK"
        elif risk_score >= self.review_threshold:
            verdict = "REVIEW"
        else:
            verdict = "ALLOW"

        latency_ms = (time.perf_counter() - start_time) * 1000.0

        return {
            "verdict": verdict,
            "risk_score": round(risk_score, 4),
            "match_count": len(matched_rules),
            "matched_rules": matched_rules,
            "latency_ms": round(latency_ms, 3)
        }

    def evaluate_request_record(self, record: Dict[str, Any]) -> Dict[str, Any]:
        """
        Evaluates a structured request dictionary (as generated by HTTPRequestParser).
        """
        # Inspect full concatenated payload (path, query, body)
        payload = str(record.get("full_payload", ""))
        result = self.evaluate_payload(payload)
        return result

    def evaluate_dataframe(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Batch evaluation across an entire dataset for benchmark reporting.
        """
        verdicts = []
        scores = []
        match_counts = []
        latencies = []

        for _, row in df.iterrows():
            payload = str(row.get("full_payload", ""))
            res = self.evaluate_payload(payload)
            verdicts.append(res["verdict"])
            scores.append(res["risk_score"])
            match_counts.append(res["match_count"])
            latencies.append(res["latency_ms"])

        eval_df = df.copy()
        eval_df["rule_verdict"] = verdicts
        eval_df["rule_score"] = scores
        eval_df["rule_match_count"] = match_counts
        eval_df["rule_latency_ms"] = latencies
        return eval_df
